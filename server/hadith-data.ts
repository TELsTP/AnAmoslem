export function getDailyHadith(): Hadith {
  const dayOfYear = Math.floor((Date.now() - new Date(new Date().getFullYear(), 0, 0).getTime()) / 86400000);
  return HADITH_DATA[dayOfYear % HADITH_DATA.length];
}

export function getHadithByTopic(topic: string): Hadith[] {
  return HADITH_DATA.filter(h => h.topic === topic);
}

export function searchHadith(query: string): Hadith[] {
  const q = query.trim().toLowerCase();
  if (!q) return HADITH_DATA;
  return HADITH_DATA.filter(h =>
    h.arabic.includes(q) ||
    h.narrator.includes(q) ||
    h.source.toLowerCase().includes(q) ||
    h.topicLabel.includes(q)
  );
}
